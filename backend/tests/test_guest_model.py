"""Guest-mode columns on users and /auth/me for a guest (spec 2026-11-20 mehmon rejimi §1)."""
import importlib.util
import uuid
from datetime import datetime, timezone
from pathlib import Path

import pytest
from fastapi.testclient import TestClient

from app.api.v1.deps import get_current_active_user
from app.main import app
from app.models.user import User
from app.schemas.auth import UserOut

_MIGRATION = Path(__file__).resolve().parents[1] / "alembic" / "versions" / "1786000052_users_guest_mode.py"


def _guest() -> User:
    return User(
        id=uuid.uuid4(),
        is_guest=True,
        is_active=True,
        language="uz",
        is_admin=False,
        created_at=datetime.now(timezone.utc),
    )


def test_migration_chain():
    spec = importlib.util.spec_from_file_location("m_1786000052", _MIGRATION)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    assert (m.revision, m.down_revision) == ("1786000052", "1786000051")


def test_user_model_has_guest_columns():
    cols = User.__table__.c
    assert cols.is_guest.nullable is False and cols.is_guest.server_default.arg == "false"
    assert cols.last_seen_at.nullable is True and cols.last_seen_at.type.timezone is True
    assert cols.registered_at.nullable is True and cols.registered_at.type.timezone is True
    # The migration's partial index is declared on the model too, so an
    # autogenerated migration does not try to drop it.
    idx = {i.name: i for i in User.__table__.indexes}["ix_users_is_guest"]
    assert [c.name for c in idx.columns] == ["id"]
    assert str(idx.dialect_options["postgresql"]["where"]) == "is_guest"


def test_user_out_carries_is_guest():
    u = _guest()
    assert UserOut.model_validate(u).is_guest is True
    assert UserOut.model_fields["is_guest"].default is False


@pytest.fixture
def client():
    guest = _guest()
    app.dependency_overrides[get_current_active_user] = lambda: guest
    yield TestClient(app)
    app.dependency_overrides.clear()


def test_me_for_guest(client):
    body = client.get("/api/v1/auth/me").json()
    assert body["is_guest"] is True
    assert body["phone"] is None and body["username"] is None and body["name"] is None
    assert body["is_admin"] is False


def test_user_out_unflushed_user_is_not_a_guest():
    # A User() built in a route and not yet flushed has is_guest None (the
    # column default fills it at INSERT); it serialises as a registered user.
    u = User(id=uuid.uuid4(), language="uz", is_admin=False, created_at=datetime.now(timezone.utc))
    assert UserOut.model_validate(u).is_guest is False
